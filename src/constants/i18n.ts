export function t(lang: Language, key: string, vars?: Record<string, string | number>): string {
  let str = TRANSLATIONS[lang][key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, String(v));
    });
  }
  return str;
}

